// ============== 辅助函数 ==============
static uint32_t bswap32(uint32_t x) {
    return __builtin_bswap32(x);
}

static void setBitRange(uint8_t *buf, int start, int nbits, int val) {
    for (int i = 0; i < nbits; i++) {
        int pos = start + i;
        int byteIdx = (pos >> 3) + 1; // buf index 1-based
        int mask = 1 << (7 - (pos & 7));
        if ((val >> (nbits - 1 - i)) & 1)
            buf[byteIdx] |= mask;
        else
            buf[byteIdx] &= ~mask & 0xFF;
    }
}

static void bfDecryptBlockLE(BF_KEY *cipher, uint8_t *block8) {
    // x86 风格: 块内两个 32-bit 字按小端解释
    uint8_t be[8];
    // swap each word
    for (int i = 0; i < 4; i++) { be[i] = block8[3-i]; be[i+4] = block8[7-i]; }
    BF_ecb_encrypt(be, be, cipher, BF_DECRYPT);
    for (int i = 0; i < 4; i++) { block8[i] = be[3-i]; block8[i+4] = be[7-i]; }
}

// ============== Banapass 解析 ==============

int32_t banapassDecode(const uint8_t block1[16], int *keynumOut) {
    // 检查版本
    if ((block1[0] | (block1[1] << 8)) != 0x0200)
        return -1;

    // 匹配密钥名 NBGIC0..7
    char name[7];
    memcpy(name, block1 + 2, 6);
    name[6] = 0;
    int keynum = -1;
    for (int i = 0; i < 8; i++) {
        if (strncmp(name, (const char*[]){"NBGIC0","NBGIC1","NBGIC2","NBGIC3","NBGIC4","NBGIC5","NBGIC6","NBGIC7"}[i], 6) == 0)
        { keynum = i; break; }
    }
    if (keynum < 0) return -1;
    if (keynumOut) *keynumOut = keynum;

    // Blowfish 解密
    uint8_t head[16];
    memcpy(head, block1, 16);
    BF_KEY bf;
    BF_set_key(&bf, 56, NBGIC_KEY[keynum]);
    bfDecryptBlockLE(&bf, head + 8);

    // BCC 校验
    uint8_t chk = 0;
    for (int i = 0; i < 7; i++) chk ^= head[8 + i];
    if (chk != head[15]) return -1;

    // 提取 NamcoID (小端)
    return (int32_t)(head[8] | (head[9] << 8) | (head[10] << 16) | (head[11] << 24));
}

QString banapassEncodeAccessCode(int keynum, uint32_t namcoId) {
    if (keynum < 0 || keynum >= 8) return {};
    const ACKey &ak = AC_KEYS[keynum];

    uint32_t prod = ak.prefix;
    uint32_t appdata = 0;

    uint8_t bcc = 0;
    for (int i = 0; i < 4; i++) {
        bcc ^= (prod >> (8*i)) & 0xFF;
        bcc ^= (appdata >> (8*i)) & 0xFF;
        bcc ^= (namcoId >> (8*i)) & 0xFF;
    }

    prod = ((prod & 3) << 8) | ((prod >> 2) & 0xFF);

    uint8_t data[8] = {};
    setBitRange(data, 0,  2,  (bcc % 11) & 3);
    setBitRange(data, 2,  10, prod);
    setBitRange(data, 12, 4,  appdata);
    // namcoId LE → BE (Python: struct.pack("<I", namco_id) unpack as >I)
    setBitRange(data, 16, 32, bswap32(namcoId));
    setBitRange(data, 48, 8,  bcc);

    // 置换
    uint8_t temp[8] = {};
    for (int i = 0; i < 56; i++) {
        int bIdx = (i >> 3) + 1;
        int bit  = 7 - (i & 7);
        if (data[bIdx] & (1 << bit)) {
            int p = ak.perm[i] % 56;
            temp[(p >> 3) + 1] |= (1 << (7 - (p & 7)));
        }
    }

    // temp 按 BE 解释为 uint64
    uint64_t res = 0;
    for (int i = 0; i < 8; i++) res = (res << 8) | temp[i];

    // numKey: pack LE, interpret as BE (Python: int.from_bytes(struct.pack("<Q", numkey), "big"))
    uint8_t nkBytes[8];
    uint64_t nk = ak.numKey;
    for (int i = 0; i < 8; i++) {
        nkBytes[i] = (nk >> (8*i)) & 0xFF;
    }
    uint64_t numKeyBE = 0;
    for (int i = 0; i < 8; i++) numKeyBE = (numKeyBE << 8) | nkBytes[i];

    res += numKeyBE;

    // 格式化为 20 位: prefix + 17 位数字
    return QString::fromLatin1(ak.prefixStr)
           + QString::number(res).rightJustified(17, QLatin1Char('0'));
}

// ============== IDM 转卡号 ==============

QString idmToAccessCode(const uint8_t uid[8]) {
    uint64_t val = 0;
    for (int i = 0; i < 8; i++)
        val = (val << 8) | uid[i];

    uint8_t out[16] = {};  // 前 6 字节为 0
    for (int i = 0; i < 10; i++) {
        uint8_t lo = (uint8_t)(val % 10);
        val /= 10;
        uint8_t hi = (uint8_t)(val % 10);
        val /= 10;
        out[15 - i] = (uint8_t)((hi << 4) | lo);
    }

    // 后 10 字节作为 HEX 字符串
    QByteArray cardNum;
    for (int i = 6; i < 16; i++)
        cardNum.append(QString::asprintf("%02X", out[i]).toLatin1());

    return QString::fromLatin1(cardNum);
}
