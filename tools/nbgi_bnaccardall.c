void SetBitRange(LPVOID lpBuffer, int nStart, size_t nBits, int dwData) {
    for (size_t i = 0; i < nBits; i++) {
        unsigned int newByte =
            (1 << (7 - (nStart + i) % 8)) | ((LPBYTE)lpBuffer)[((nStart + i) >> 3) + 1];
        if ((dwData & (1 << (nBits - 1 - i))) == 0) newByte = ~newByte;
        ((LPBYTE)lpBuffer)[((nStart + i) >> 3) + 1] = newByte & 0xff;
    }
}

void SetRandNumData(LPVOID lpBuffer, DWORD dwRandNum) { SetBitRange(lpBuffer, 0, 2, dwRandNum); }
void SetProductData(LPVOID lpBuffer, DWORD dwProduct) { SetBitRange(lpBuffer, 2, 10, dwProduct); }
void SetAppData(LPVOID lpBuffer, DWORD dwAppData) { SetBitRange(lpBuffer, 12, 4, dwAppData); }
void SetNamcoIDData(LPVOID lpBuffer, DWORD dwNamcoId) { SetBitRange(lpBuffer, 16, 32, dwNamcoId); }
void SetBCCData(LPVOID lpBuffer, DWORD dwBcc) { SetBitRange(lpBuffer, 48, 8, dwBcc); }

void LShift(LPBYTE lpBuffer) {
    for (int i = 0; i < 8; i++) {
        lpBuffer[i] <<= 1;
        if (i != 7 && lpBuffer[i + 1] & 0x80) lpBuffer[i] |= 1;
    }
}

int NbgiGetAccessCode(char *AccessCode, const void *HeaderData, int *NbgiSerial) {
    char strAC[32];
    struc_1 tCard;

    if (BNACCardDecode(&tCard, HeaderData)) return 0;
    if (BNACCardEncodeAccessCode(strAC, tCard.m_KeyNum, tCard.m_Serial)) return 0;

    strncpy(AccessCode, strAC, 20);
    AccessCode[20] = 0;
    if (NbgiSerial != NULL) *NbgiSerial = tCard.m_Serial;
    return 1;
}

int BNACCardDecode(struc_1 *Decoded, const void *HeaderData) {
    if (!Decoded || !HeaderData) return -1;

    BYTE head[16];
    memcpy(head, HeaderData, sizeof head);
    PBLOWFISH_KEY Buf2 = s_DataKeyNBGIC;

    UINT8 keynum;
    for (keynum = 0; keynum < 8; keynum++)
        if (memcmp(&head[2], s_DataKeyNBGIC[keynum].m_Name, 6) == 0) break;
    if (keynum == _countof(s_DataKeyNBGIC)) return -1;

    if (*((LPWORD)&head[0]) != BNACCardVersion) return -2;

    BNACCardBFDec(s_DataKeyNBGIC[keynum].m_Key, 8, &head[8]);
    BYTE chk = 0;
    for (int j = 0; j < 7; ++j) chk ^= head[j + 8];
    if (chk != head[15]) return -2;

    Decoded->m_Serial = *((LPDWORD)&head[8]);
    Decoded->Unk04 = *((LPWORD)&head[12]);
    Decoded->Unk06 = head[14];
    Decoded->m_KeyNum = keynum;
    return 0;
}
void BNACCardBFDec(LPBYTE lpKey, size_t nBytes, LPBYTE lpData) {
    BlowfishSetKey(lpKey, 448);
    for (size_t i = 0; i < (nBytes / 8); ++i) BlowfishDecrypt((LPDWORD)&lpData[i * 8], (LPDWORD)&lpData[i * 8 + 4]);
}

